/**
 * Формат времени забега для секундомера в HUD и для экрана результата.
 *
 * Общий модуль, а не метод одного из них: иначе на двух экранах одно и то же
 * время рисовалось бы по-разному, а рассинхрон такого рода замечают не сразу.
 *
 * Формат M:SS — минуты без ведущего нуля, секунды с ним. Забег в прототипе идёт
 * единицы минут, поэтому часы не нужны; при переполнении за 60 минут минуты
 * просто продолжат расти («73:20»), а не обнулятся.
 */
export function formatRunTime(seconds: number): string {
  const total = Math.max(0, Math.floor(seconds));
  const minutes = Math.floor(total / 60);
  const rest = total % 60;
  return `${minutes}:${rest < 10 ? '0' : ''}${rest}`;
}

/**
 * Формат накопленного времени для экрана статистики: там суммируются все
 * вылазки, и часы набегают за один вечер.
 *
 * До часа — тот же M:SS, что в секундомере: время вылазки игрок читает именно в
 * этом виде, и второй формат для тех же величин сбивал бы. От часа — «2 ч 13
 * мин»: «133:20» о двух часах не говорит ничего, а секунды в такой сумме уже
 * ничего не значат.
 */
export function formatTotalTime(seconds: number): string {
  const total = Math.max(0, Math.floor(seconds));
  if (total < 3600) return formatRunTime(total);

  const hours = Math.floor(total / 3600);
  const minutes = Math.floor((total % 3600) / 60);
  return `${hours} ч ${minutes} мин`;
}
