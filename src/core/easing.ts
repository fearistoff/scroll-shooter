/**
 * Кривая скорости cubic-bezier(x1, y1, x2, y2) — ровно та же, что в CSS
 * transition-timing-function.
 *
 * Нужна там, где движение считается в игровом цикле, а не браузером: полёт
 * подобранного кристалла к счётчику (PickupPool). Взять CSS-переход туда нельзя —
 * объект не DOM-элемент, а инстанс в InstancedMesh, и шагает он по игровому dt
 * (значит замирает на паузе и на экранах вместе со всем остальным).
 *
 * Кривая задана двумя контрольными точками, концы закреплены в (0,0) и (1,1).
 * По входному t (доля времени) нужна y (доля пути), но кривая параметрическая:
 * и x, и y считаются от собственного параметра s. Поэтому сначала решается
 * x(s) = t, и только потом берётся y(s) — так же это делают браузеры.
 *
 * Решение — метод Ньютона от начального приближения s = t. При x1, x2 в [0, 1]
 * функция x(s) монотонна, и четырёх итераций хватает с запасом: ЗАМЕРЕНО для
 * cubic-bezier(.25,.75,.75,.25) сравнением с бисекцией на 1001 точке —
 * максимальная ошибка 2.1e-6, и та же самая при трёх итерациях и при пяти. То
 * есть точность здесь упирается не в число шагов, а в порог выхода ниже, и
 * запас по нему такой, что на любом пути это доли пикселя.
 */
export function cubicBezierEase(
  x1: number,
  y1: number,
  x2: number,
  y2: number,
  t: number,
): number {
  // Концы закреплены: за пределами отрезка кривая не определена, а вызывающий
  // может передать t чуть больше 1 на последнем шаге.
  if (t <= 0) return 0;
  if (t >= 1) return 1;

  let s = t;
  for (let i = 0; i < 4; i++) {
    const error = bezier(x1, x2, s) - t;
    if (Math.abs(error) < 1e-6) break;

    const slope = bezierSlope(x1, x2, s);
    // Горизонтальный участок: делить на него нельзя, а приближение уже
    // настолько близко, насколько кривая позволяет.
    if (Math.abs(slope) < 1e-6) break;

    s -= error / slope;
    if (s < 0) s = 0;
    else if (s > 1) s = 1;
  }

  return bezier(y1, y2, s);
}

/** Координата кубической кривой Безье с концами 0 и 1. */
function bezier(a: number, b: number, s: number): number {
  const inv = 1 - s;
  return 3 * inv * inv * s * a + 3 * inv * s * s * b + s * s * s;
}

/** Производная той же кривой по параметру — для шага Ньютона. */
function bezierSlope(a: number, b: number, s: number): number {
  const inv = 1 - s;
  return 3 * inv * inv * a + 6 * inv * s * (b - a) + 3 * s * s * (1 - b);
}
