/** Что опыту нужно от забега: во сколько раз дороже опыт текущей волны и куда его класть. */
export interface ExpSinkRun {
  readonly expMultiplier: number;
  addExp(amount: number): void;
}

/**
 * Опыт с убитых зомби, разбитых бочек и босса (ТЗ раздел 9).
 *
 * НА ЭКРАНЕ ОПЫТ НЕ ПОКАЗЫВАЕТСЯ ВОВСЕ: награда попадает в счётчик HUD прямо в
 * момент смерти. Ни объекта на дороге, ни полёта к плашке нет — забег в поздних
 * волнах роняет опыт десятками раз в секунду, и поток летящих кристаллов
 * закрывал бы дорогу ровно там, где по ней важнее всего смотреть. Деньги летят
 * по-прежнему (MoneyPool): они выпадают не с каждого убийства, и их поток
 * дорогу не застилает.
 *
 * ЕДИНСТВЕННАЯ ТОЧКА, где к номиналу применяется множитель волны
 * (RunState.expMultiplier). Источники — зомби, бочки, босс — передают сюда
 * БАЗОВОЕ число из CONFIG.exp и о волне не знают: иначе множитель пришлось бы
 * дублировать в трёх воронках смерти, и он разъехался бы при первой правке.
 *
 * Множитель берётся в момент начисления, то есть в волне, в которой награду
 * заслужили. Для босса это не тонкость, а необходимость: он умирает последним в
 * волне, и отложенное начисление считалось бы уже по следующей.
 */
export class ExpSink {
  /** Сколько раз за забег что-то дало опыт — для отладки и замерочных скриптов. */
  private dropsTotal = 0;
  /** Сколько опыта начислено за забег, уже с множителем волны. */
  private valueTotal = 0;

  constructor(private readonly run: ExpSinkRun) {}

  get drops(): number {
    return this.dropsTotal;
  }

  get value(): number {
    return this.valueTotal;
  }

  /**
   * Награда за убитого зомби, разбитую бочку или кусок босса.
   *
   * x и z не используются: места выпадения у награды больше нет, — но остаются в
   * сигнатуре, потому что воронки смерти знают только точку и не должны знать,
   * показывается опыт на дороге или нет. Вернуть предмет — значит поменять эту
   * подсистему, а не три места вызова.
   */
  award(_x: number, _z: number, value: number): void {
    const amount = value * this.run.expMultiplier;
    this.run.addExp(amount);
    this.valueTotal += amount;
    this.dropsTotal++;
  }

  /** Обнуляет счётчики забега. Зовётся из Game.startRun вместе с остальными. */
  reset(): void {
    this.dropsTotal = 0;
    this.valueTotal = 0;
  }

  /** Состояние — для отладки и замерочных скриптов (__game.exp). */
  debugSnapshot(): { drops: number; value: number; waveMultiplier: number } {
    return {
      drops: this.dropsTotal,
      value: +this.valueTotal.toFixed(2),
      waveMultiplier: +this.run.expMultiplier.toFixed(3),
    };
  }
}
