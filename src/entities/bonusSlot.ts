/**
 * Источник бонусов с точки зрения слота: важно только, есть ли у него что-то на
 * поле. И `BarrelField`, и `GateField` уже отдают `activeCount`, поэтому ничего
 * специально под слот они не реализуют.
 */
export interface BonusSource {
  /** Сколько объектов этого источника сейчас на поле. */
  readonly activeCount: number;
}

/**
 * Слот бонуса: на экране одновременно допустим ОДИН бонус — бочка ИЛИ ворота.
 *
 * Стена типа A из двух секций и колонна турникетов типа B считаются одним
 * бонусом: их части выезжают одним вызовом спавна, и слот проверяется до него.
 *
 * Правило вынесено в отдельный объект, а не сделано взаимной проверкой «а что у
 * соседа»: бочкам понадобились бы ворота, а воротам бочки, и две подсистемы
 * замкнулись бы друг на друга. Здесь зависимость односторонняя — поля знают про
 * слот, слот знает только про «сколько у вас активных».
 *
 * Спавн ЗАПРАШИВАЮТ только потоки (`spawnStream`): явный `spawn()` из отладки и
 * замеров слот не проверяет, иначе детерминированные прогоны стало бы нельзя
 * ставить в нужную позицию.
 */
export class BonusSlot {
  private readonly sources: BonusSource[] = [];

  /** Подключает источник бонусов. Вызывается один раз при сборке игры. */
  add(source: BonusSource): void {
    this.sources.push(source);
  }

  /** Свободен ли экран — можно ли выпускать следующий бонус. */
  get isFree(): boolean {
    for (const source of this.sources) {
      if (source.activeCount > 0) return false;
    }
    return true;
  }
}
