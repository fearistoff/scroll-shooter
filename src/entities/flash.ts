import { Color } from 'three';
import { CONFIG } from '../config';

/** Белый — к нему подмешивается собственный цвет цели. Один на весь модуль. */
const WHITE = new Color(0xffffff);

/**
 * Цвет вспышки при получении урона: СВЕТЛЫЙ ОТТЕНОК собственного цвета цели, а не
 * общий посторонний цвет.
 *
 * Так вспышка читается на любой цели и ни у кого не меняет опознавательный цвет:
 * зелёный зомби светлеет в светло-зелёный, коричневый — в светло-коричневый,
 * синий герой — в голубой. Общий красный тон, стоявший здесь раньше, на миг делал
 * всех одинаковыми.
 *
 * ПОТОЛОК — БЕЛЫЙ, и это ограничение не обойти: у зомби и союзников цвет задан
 * через instanceColor, который three УМНОЖАЕТ на цвет материала, а умножение
 * только гасит. Поэтому светлее белого вспышка стать не может, и у изначально
 * светлых целей (союзники, 0xd8d2c4) запас контраста самый маленький — см. замер
 * в комментарии к CONFIG.ui.damageFlash.lighten.
 *
 * Цвет считается ОДИН раз на цель при создании: в цикле отрисовки, который идёт
 * каждый кадр для каждого инстанса, аллокации недопустимы.
 */
export function makeFlashColor(baseHex: number): Color {
  return new Color(baseHex).lerp(WHITE, CONFIG.ui.damageFlash.lighten);
}
