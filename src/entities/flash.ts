import { Color } from 'three';
import { CONFIG } from '../config';

/** Белый — к нему подмешивается собственный цвет цели. Один на весь модуль. */
const WHITE = new Color(0xffffff);

/**
 * Цвет вспышки при получении урона: СВЕТЛЫЙ ОТТЕНОК собственного цвета цели, а не
 * общий посторонний цвет.
 *
 * Так вспышка читается на любой цели и ни у кого не меняет опознавательный цвет:
 * зелёный зомби светлеет в светло-зелёный, коричневый — в светло-коричневый,
 * фиолетовый герой — в сиреневый. Общий красный тон, стоявший здесь раньше, на миг
 * делал всех одинаковыми.
 *
 * ПОТОЛОК — БЕЛЫЙ, и это ограничение не обойти: у зомби и союзников цвет задан
 * через instanceColor, который three УМНОЖАЕТ на цвет материала, а умножение
 * только гасит. Поэтому светлее белого вспышка стать не может, и чем светлее
 * собственный цвет цели, тем меньше у неё запас контраста — из-за этого базовые
 * цвета отряда подобраны небелыми, см. замеры в комментариях к
 * CONFIG.player.colors и CONFIG.ui.damageFlash.lighten.
 *
 * Цвет считается ОДИН раз на цель при создании: в цикле отрисовки, который идёт
 * каждый кадр для каждого инстанса, аллокации недопустимы.
 */
export function makeFlashColor(baseHex: number): Color {
  return new Color(baseHex).lerp(WHITE, CONFIG.ui.damageFlash.lighten);
}

/**
 * Вспышка для моделей с ВЕРТЕКСНЫМИ цветами (боец отряда, entities/soldier.ts).
 *
 * У таких моделей опознавательные цвета запечены в геометрию, а материал и
 * instanceColor — белые МНОЖИТЕЛИ поверх. Потолок-белый из makeFlashColor тут
 * не работает: белый множитель — это тождество, и вспышки не было бы вовсе.
 * Поэтому множитель больше единицы: компоненты выше 1 для three легальны,
 * каждая деталь фигурки на вспышке приподнимается к своей светлой версии, а
 * итог кадра зажимается на выводе сам.
 *
 * Коэффициент — 1 + 3 × lighten: тройка подобрана ГЛАЗОМ по фигурке бойца
 * (при lighten 0.2 это ×1.6 — куртка и штаны светлеют заметно, чёрные ботинки
 * едва), замером, как цвета капсул, не проверялась.
 */
export function makeModelFlashColor(): Color {
  const k = 1 + 3 * CONFIG.ui.damageFlash.lighten;
  return new Color(k, k, k);
}

/** Чёрный — к нему подмешивается собственный цвет тела. Один на весь модуль. */
const BLACK = new Color(0x000000);

/**
 * Цвет ТЕЛА: тёмный оттенок собственного цвета убитого (deathAnim.corpseDarken).
 *
 * Зачем: тела остаются лежать там, где юнит стоял, и в живом цвете куча трупов
 * читается как толпа — взгляд принимает их за цели. Затемнение отделяет мёртвых
 * от живых, не отбирая опознавательный цвет: крупный зомби остаётся коричневым,
 * обычный — зелёным, просто тёмными.
 *
 * Умножению instanceColor это не мешает (в отличие от вспышки, которой белый
 * материал нужен как потолок): затемнение гасит, а гасить умножение умеет.
 *
 * Считается ОДИН раз на цель при создании: в цикле отрисовки аллокации недопустимы.
 */
export function makeCorpseColor(baseHex: number): Color {
  return new Color(baseHex).lerp(BLACK, CONFIG.deathAnim.corpseDarken);
}
